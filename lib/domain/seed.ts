const base = Date.UTC(2026, 8, 1, 12);
function demand(
  id: string,
  title: string,
  category: CategoryId,
  loc: number,
  votes: number,
  pledgers: number,
  check: number,
  needs: string[],
  description: string,
  dx = 0,
  dy = 0,
): Demand {
  const l = locations[loc];
  return {
    id,
    title,
    category,
    location: l.name,
    district: l.district,
    lat: l.lat + dx,
    lng: l.lng + dy,
    description,
    needs,
    avgCheck: check,
    seedVotes: votes,
    seedPledgers: pledgers,
    seedPledgeTotal: pledgers * 3000,
    votes,
    pledgers,
    pledgeTotal: pledgers * 3000,
    testVotes: 0,
    supported: false,
    myPledge: 0,
    ownerId: null,
    isDemo: true,
    status: "published",
    reason: null,
    mergedInto: null,
    createdAt: base + Number(id.slice(1)) * 3600000,
    offerCount: id === "d1" ? 2 : 0,
  };
}
